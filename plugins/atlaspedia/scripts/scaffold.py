DEFAULT_PAGES_DIR = "pages/"
TOPIC_FILES = ("PLAN.md", "topic.json", "tmp")  # owned by the workflow, never written by the scaffold
THEME_TOKENS = {"accent": ("accent",), "soft": ("accentSoft",), "accent-soft": ("accentSoft",),
                "dark": ("dark", "accent"), "dark-accent": ("dark", "accent"),
                "dark-soft": ("dark", "accentSoft"), "dark-accent-soft": ("dark", "accentSoft")}
DEFAULT_PLACEHOLDER = "Search modules, sections & terms  ( / )"
DEFAULT_FOOTNOTE = ("Every fact, number and figure on these pages cites its source; what the sources do not establish is marked as not specified or not available. Details change over time; confirm against the linked original documentation before relying on them.")
DEFAULT_LEVELS = {"1": "Foundations", "2": "Practical engineering", "3": "Advanced topics", "4": "Research frontier"}


def normalise_pages_dir(value: str | None) -> str:
    if value is None:
        return DEFAULT_PAGES_DIR
    v = value.strip().strip("`").replace("\\", "/").strip()
    if v.lower() in ("", "flat", "none", "-", "—", "."):
        return ""
    v = v.strip("/") + "/"
    return v


def parse_levels(value: str) -> dict:
    out = {}
    for part in re.split(r"\s*[·;,]\s*", value.strip()):
        m = re.match(r"^(\d)\s+(.+)$", part.strip())
        if m:
            out[m.group(1)] = m.group(2).strip()
    return out


def parse_theme(value: str, plan_path: Path, line: int, rep: Report) -> dict | None:
    """`accent #0b5cad · soft #e2ecf8 · dark #6aa8ff · dark-soft #16263d` -> site.json theme object."""
    theme: dict = {}
    for part in re.split(r"\s*[·;,]\s*", value.strip()):
        if not part:
            continue
        m = re.match(r"^([a-z-]+)\s*[:=]?\s*(\S+)$", part.strip(), re.I)
        if not m or m.group(1).lower() not in THEME_TOKENS:
            rep.error(plan_path, line, f"Theme part `{part}` must be `accent|soft|dark|dark-soft #hex`")
            continue
        colour = m.group(2)
        if not HEX_COLOUR_RE.match(colour):
            rep.error(plan_path, line, f"Theme `{m.group(1)}` must be a CSS hex colour like #0b5cad (got `{colour}`)")
            continue
        keys = THEME_TOKENS[m.group(1).lower()]
        target = theme
        for k in keys[:-1]:
            target = target.setdefault(k, {})
        target[keys[-1]] = colour
    return theme or None


def parse_hours(value: str):
    """F4 study planner: an `Hours` cell -> number (`25`, `25 h`, `≈ 22.5`) or the midpoint of a range (`20–30`, `20-30 h`);
    None when the cell is not a number or a range."""
    if not re.fullmatch(r"[\s≈~]*\d+(?:[.,]\d+)?(?:\s*[–\-—]\s*\d+(?:[.,]\d+)?)?\s*(?:h|hours?|hrs?)?\s*", value, re.I):
        return None
    vals = [float(n.replace(",", ".")) for n in re.findall(r"\d+(?:[.,]\d+)?", value)]
    v = sum(vals) / len(vals)
    if v <= 0:
        return None
    return int(v) if v.is_integer() else round(v, 2)


# I4 derived policies: `**A11y**: font dyslexic · scale 1.15 · motion reduced · contrast high` (any subset, any order)
# -> site.json `a11y` (contracts §7, §8). `none` / `default` / empty -> no key. Values are checked against A11Y_VALUES.
def parse_a11y(value: str, plan_path: Path, line: int, rep: Report) -> dict | None:
    a11y: dict = {}
    if value.strip().lower() in ("", "none", "default", "defaults", "-", "—"):
        return None
    for part in re.split(r"\s*[·;,]\s*", value.strip()):
        if not part:
            continue
        m = re.match(r"^([a-z]+)\s*[:=]?\s*(\S+)$", part.strip(), re.I)
        if not m or m.group(1).lower() not in A11Y_VALUES:
            rep.error(plan_path, line, f"A11y part `{part}` must be `font|scale|motion|contrast <value>`")
            continue
        key, raw_val = m.group(1).lower(), m.group(2).strip().lower()
        allowed = A11Y_VALUES[key]
        if key == "scale":
            try:
                val = float(raw_val.rstrip("x×"))
            except ValueError:
                val = None
            val = next((a for a in allowed if val is not None and abs(val - a) < 1e-9), None)
        else:
            val = raw_val if raw_val in allowed else None
        if val is None:
            want = ", ".join(str(a) for a in allowed[:-1]) + f" or {allowed[-1]}"
            rep.error(plan_path, line, f"A11y {key} must be {want} (got `{m.group(2)}`)")
            continue
        a11y[key] = val
    return a11y or None


def registry_from_plan(plan_path: Path, rep: Report) -> dict | None:
    lines = read_lines(plan_path)
    secs = sections(lines)
    first = secs[0][1] if secs else len(lines)
    raw = header_keys(lines, 0, first)
    keys = {k: strip_code(v[0]) for k, v in raw.items()}
    title = keys.get("Title") or ""
    if not title:
        m = next((re.match(r"^# Site plan: (.+)$", l.strip()) for l in lines if l.strip()), None)
        title = m.group(1).strip() if m else ""
    if not title:
        rep.error(plan_path, 1, "SITE_PLAN needs `**Title**: …` (or `# Site plan: <Title>`)")
    slug = keys.get("Slug", "")
    prefix = keys.get("Prefix") or slug or re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")[:40] or "atlaspedia-site"
    levels = parse_levels(keys["Levels"]) if keys.get("Levels") else DEFAULT_LEVELS
    if keys.get("Levels") and not levels:
        rep.error(plan_path, raw["Levels"][1] + 1, "Levels must look like `1 Foundations · 2 Practical …`")
    fmt = (keys.get("Format") or "site").strip().lower()
    if fmt not in ("single", "site"):
        rep.error(plan_path, raw["Format"][1] + 1, f"Format must be single or site (got `{keys.get('Format')}`)")
        fmt = "site"
    budget = 250
    if keys.get("Budget"):
        m = re.match(r"^\s*(\d+)\s*(KB|kB|kb)?\s*$", keys["Budget"])
        if m:
            budget = int(m.group(1))
        else:
            rep.error(plan_path, raw["Budget"][1] + 1, f"Budget must look like `250 KB` (got `{keys['Budget']}`)")
    pages_dir = "" if fmt == "single" else normalise_pages_dir(keys.get("Pages dir"))
    sec = find_section(secs, "Pages")
    if sec is None:
        rep.error(plan_path, 1, "section `## Pages` missing")
        return None
    t = find_table(lines, sec[1] + 1, sec[2])
    if t is None:
        rep.error(plan_path, sec[1] + 1, "Pages table missing")
        return None
    header, hidx, rows = t
    ci = {n: col_index(header, n) for n in ("File", "Num", "Title", "Group", "Level", "Desc")}
    for n, i in ci.items():
        if i < 0:
            rep.error(plan_path, hidx + 1, f"Pages table has no `{n}` column")
    if rep.errors:
        return None
    hours_col = col_index(header, "Hours")   # F4 study planner: optional `Hours` column -> pages[].hours
    pages, seen = [], set()
    for idx, cells in rows:
        def cell(n):
            i = ci[n]
            return cells[i] if i < len(cells) else ""
        file = strip_code(cell("File"))
        if not file.endswith(".html"):
            rep.error(plan_path, idx + 1, f"File `{file}` must end with .html")
            continue
        if "/" in file or "\\" in file:
            rep.error(plan_path, idx + 1, f"File `{file}` must be a bare file name (pages live under {pages_dir or 'the site root'})")
            continue
        if file in seen:
            rep.error(plan_path, idx + 1, f"duplicate page file `{file}`")
        seen.add(file)
        entry = {"file": file, "num": cell("Num"), "title": cell("Title"), "group": cell("Group")}
        if not entry["num"] or not entry["title"] or not entry["group"]:
            rep.error(plan_path, idx + 1, "Num, Title and Group must be filled")
        lvl = cell("Level").strip("—–- ")
        if lvl.isdigit():
            entry["level"] = int(lvl)
            if lvl not in levels:
                rep.error(plan_path, idx + 1, f"level {lvl} is not named in `**Levels**`")
        entry["desc"] = cell("Desc")
        if not entry["desc"]:
            rep.warn(plan_path, idx + 1, f"`{file}` has no Desc (used by the curriculum map and search)")
        # F4 study planner: `Hours` cell -> pages[].hours (`25`, or a range `20–30` -> its midpoint); empty or `—` = none
        hv = strip_code(cells[hours_col]) if 0 <= hours_col < len(cells) else ""
        if hv and hv not in ("—", "–", "-"):
            hours = parse_hours(hv)
            if hours is None:
                rep.error(plan_path, idx + 1, f"Hours `{hv}` must be a number or a range like `20–30`")
            else:
                entry["hours"] = hours
        pages.append(entry)
    if not any(p["file"] == "index.html" for p in pages):
        rep.error(plan_path, hidx + 1, "Pages must include index.html")
    if fmt == "single":
        if len(pages) != 1:
            rep.error(plan_path, hidx + 1, f"single format: Pages must list exactly one page, index.html (got {len(pages)})")
    elif not any(p["file"] == "glossary.html" for p in pages):
        rep.warn(plan_path, hidx + 1, "Pages does not include glossary.html")
    reg = {
        "title": title,
        "subtitle": keys.get("Subtitle") or "Interactive Research Report",
        "storagePrefix": prefix,
        "home": "index.html",
        "pagesDir": pages_dir,
        "searchPlaceholder": keys.get("Search placeholder") or DEFAULT_PLACEHOLDER,
        "levels": levels,
        "footnote": keys.get("Footnote") or DEFAULT_FOOTNOTE,
    }
    if fmt == "single":
        reg["mode"] = "single"
        reg["budgetKb"] = budget
    if keys.get("Theme"):
        theme = parse_theme(keys["Theme"], plan_path, raw["Theme"][1] + 1, rep)
        if theme:
            reg["theme"] = theme
    # F3 bilingual glossary (nav): optional `**Second language**: Vietnamese` header line → site.json secondLanguage
    if keys.get("Second language"):
        reg["secondLanguage"] = keys["Second language"]
    # E6 changelog + version stamp: `**Version**: 1.0` -> site.json version (every page footer, changelog.html)
    if keys.get("Version"):
        reg["version"] = keys["Version"]
    # I4 derived policies: `**Licence**: CC BY-SA 4.0` -> site.json licence (shown by the version stamp / footnote);
    # `**A11y**: …` -> site.json a11y (the reading-settings defaults). Both optional; `License` is accepted as a spelling.
    licence = keys.get("Licence") or keys.get("License")
    if licence and licence.strip().lower() not in ("none", "-", "—"):
        reg["licence"] = licence.strip()
    if keys.get("A11y"):
        a11y = parse_a11y(keys["A11y"], plan_path, raw["A11y"][1] + 1, rep)
        if a11y:
            reg["a11y"] = a11y
    reg["pages"] = pages
    return reg


def rewrite_for_pages_dir(text: str, pages_dir: str) -> str:
    """A template page moved under <pagesDir>: includes and the home link climb back to the root."""
    up = "../" * len([p for p in pages_dir.split("/") if p])
    text = re.sub(r'(href|src)="assets/', lambda m: f'{m.group(1)}="{up}assets/', text)
    text = re.sub(r'href="index\.html(?=[#"])', f'href="{up}index.html', text)
    return text


def rewrite_root_page(text: str, pages_dir: str) -> str:
    """index.html at the root: links to sibling pages now point into <pagesDir>."""
    return re.sub(r'href="(?!index\.html)([a-z0-9][a-z0-9_.-]*\.html)(?=[#"])', lambda m: f'href="{pages_dir}{m.group(1)}', text)


def sync(site: Path, rep: Report) -> list[str]:
    generated = []
    for json_name, js_name, maker, label in (("site.json", "site.js", site_js, "site"), ("glossary.json", "glossary.js", glossary_js, "glossary")):
        obj, err = load_json(site / "assets" / json_name)
        if err:
            rep.error(site / "assets" / json_name, 1, err)
            continue
        if label == "glossary" and not isinstance(obj, list):
            rep.error(site / "assets" / json_name, 1, "glossary.json must be a JSON array")
            continue
        if label == "site" and not isinstance(obj, dict):
            rep.error(site / "assets" / json_name, 1, "site.json must be a JSON object")
            continue
        if label == "site" and "theme" in obj:
            validate_theme(obj["theme"], site / "assets" / json_name, rep)
        if label == "site" and "a11y" in obj:  # I4 derived policies
            validate_a11y(obj["a11y"], site / "assets" / json_name, rep)
        (site / "assets" / js_name).write_text(maker(obj), encoding="utf-8")
        generated.append(js_name)
        print(f"generated      assets/{js_name}")
    # the per-site data file (indexes, backlinks, evidence, notation, changelog …) is rebuilt from the pages every sync
    if not rep.errors and (site / "assets" / "site.json").exists():
        from build_site_data import build as build_site_data  # noqa: E402 — same folder, imported lazily
        before = len(rep.errors)
        build_site_data(site, rep)
        if len(rep.errors) == before:
            generated.append("data.js")
            print("generated      assets/data.js")
    return generated


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("siteDir")
    ap.add_argument("--plan")
    ap.add_argument("--sync", action="store_true")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--with-styleguide", action="store_true", dest="styleguide")
    ap.add_argument("--offline", action="store_true")
    ap.add_argument("--vendor-from", dest="vendor_from")
    ap.add_argument("--template", help=argparse.SUPPRESS)
    try:
        args = ap.parse_args(argv)
    except SystemExit:
        return 2
    if not args.plan and not args.sync and not args.offline:
        return usage_error("give --plan <SITE_PLAN.md>, --sync or --offline")
    if args.vendor_from and not args.offline:
        return usage_error("--vendor-from needs --offline")
    if args.vendor_from and not Path(args.vendor_from).is_dir():
        return usage_error(f"--vendor-from: no such directory: {args.vendor_from}")
    site = Path(args.siteDir).resolve()
    template = Path(args.template).resolve() if args.template else TEMPLATE
    rep = Report("tool", "scaffold")
    copied = skipped = 0
    pages = 0
    old_reg, _ = load_json(site / "assets" / "site.json") if (site / "assets" / "site.json").exists() else (None, None)
    vendored = isinstance(old_reg, dict) and old_reg.get("vendor") is True and (site / "assets" / "vendor" / "manifest.json").exists()
    if args.plan:
        plan_path = Path(args.plan)
        if not plan_path.exists():
            return usage_error(f"no such plan: {plan_path}")
        if not template.exists():
            return usage_error(f"template folder missing: {template}")
        reg = registry_from_plan(plan_path, rep)
        if reg is None:
            return rep.finish({"copied": 0, "skipped": 0, "generated": [], "pages": 0})
        single = reg.get("mode") == "single"
        if single and not (template / SINGLE_SKELETON).exists():
            rep.error(template / SINGLE_SKELETON, 1, f"template has no {SINGLE_SKELETON} — the single-page skeleton is missing from {template}")
            return rep.finish({"copied": 0, "skipped": 0, "generated": [], "pages": 0})
        auto_pages = [a for a in AUTO_PAGES if (template / a[0]).exists()]
        if not single:
            for file, num, title, desc in auto_pages:
                if not any(p["file"] == file for p in reg["pages"]):
                    reg["pages"].append({"file": file, "num": num, "title": title, "group": "Reference", "desc": desc})
        pages_dir = reg["pagesDir"]
        if pages_dir.split("/")[0] in TOPIC_FILES:
            rep.error(plan_path, 1, f"Pages dir `{pages_dir}` collides with the topic's own `{pages_dir.split('/')[0]}`")
            return rep.finish({"copied": 0, "skipped": 0, "generated": [], "pages": 0})
        (site / "assets").mkdir(parents=True, exist_ok=True)
        if pages_dir:
            (site / pages_dir).mkdir(parents=True, exist_ok=True)
        print(f"layout         {'single page (index.html + assets/, bundled later by bundle.py)' if single else 'flat (every page beside index.html)' if not pages_dir else 'index.html at the root, pages under ' + pages_dir}")

        def place(rel: str, dst_rel: str, transform=None):
            nonlocal copied, skipped
            src, dst = template / rel, site / dst_rel
            if dst_rel.split("/")[0] in TOPIC_FILES:
                rep.error(dst, 1, f"refusing to write {dst_rel}: owned by the workflow, not the site")
                return
            if dst.exists() and not args.force:
                print(f"skip (exists)  {dst_rel}")
                skipped += 1
                return
            if transform is None:
                shutil.copyfile(src, dst)
            else:
                dst.write_text(transform(src.read_text(encoding="utf-8")), encoding="utf-8")
            print(f"copied         {dst_rel}")
            copied += 1

        if single:
            for rel in ("assets/style.css", "assets/app.js", SINGLE_SKELETON):
                place(rel, rel)
        for rel in ([] if single else ROOT_FILES):
            if rel == "index.html" and pages_dir:
                place(rel, rel, lambda t: rewrite_root_page(t, pages_dir))
            else:
                place(rel, rel)
        for rel in ([] if single else PAGE_FILES + [a[0] for a in auto_pages] + (["styleguide.html"] if args.styleguide else [])):
            if pages_dir:
                place(rel, pages_dir + rel, lambda t: rewrite_for_pages_dir(t, pages_dir))
            else:
                place(rel, rel)
        dj = site / "assets" / "data.js"
        if not dj.exists():
            dj.write_text(DATA_JS_STUB, encoding="utf-8")
            print("wrote          assets/data.js (empty stub; --sync rebuilds it from the pages)")
        gj = site / "assets" / "glossary.json"
        if gj.exists() and not args.force:
            print("skip (exists)  assets/glossary.json")
            skipped += 1
        elif args.styleguide:
            shutil.copyfile(template / "assets" / "glossary.json", gj)
            print("copied         assets/glossary.json (sample terms linking to the style guide)")
            copied += 1
        else:
            gj.write_text("[]\n", encoding="utf-8")
            print("wrote          assets/glossary.json (empty)")
        if vendored:  # G1: a vendored site stays vendored (the vendor step below re-applies the rewrite to recopied pages)
            reg["vendor"] = True
        (site / "assets" / "site.json").write_text(json.dumps(reg, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
        print(f"wrote          assets/site.json ({len(reg['pages'])} pages)")
        pages = len(reg["pages"])
    else:
        obj, err = load_json(site / "assets" / "site.json")
        pages = len(obj.get("pages", [])) if isinstance(obj, dict) else 0
    extra = {}
    if (args.offline or (args.plan and vendored)) and not rep.errors:
        from vendor import vendor_site  # noqa: E402 — G1 offline bundle, same folder
        res = vendor_site(site, Path(args.vendor_from).resolve() if args.vendor_from else None, rep=rep)
        if res is not None:
            sj = site / "assets" / "site.json"
            obj, err = load_json(sj)
            if isinstance(obj, dict) and obj.get("vendor") is not True:
                obj["vendor"] = True
                sj.write_text(json.dumps(obj, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
                print('wrote          assets/site.json ("vendor": true)')
            extra = {"vendored": res["files"], "fetched": res["fetched"], "rewritten": res["pages"]}
    generated = sync(site, rep)
    if args.plan and not rep.errors and reg.get("mode") == "single":
        print(f"\nScaffolded {site} (single page)\nNext: write index.html from _single.html, then run\n"
              f"  python {Path(__file__).resolve().parent / 'validate.py'} \"{site}\"\n"
              f"  python {Path(__file__).resolve().parent / 'bundle.py'} \"{site}\" --out <topic folder>/index.html")
    elif args.plan and not rep.errors:
        where = (site / reg["pagesDir"]) if reg["pagesDir"] else site
        print(f"\nScaffolded {site}\nNext: write the pages in {where} (copy _module.html / _synthesis.html / _reference.html per page kind), then run\n"
              f"  python {Path(__file__).resolve().parent / 'validate.py'} \"{site}\"")
    return rep.finish({"copied": copied, "skipped": skipped, "generated": generated, "pages": pages, **extra})


