#!/usr/bin/env python
"""atlaspedia scaffolder — copies the fixed template into a site folder and generates the registry files.

Usage:
  python scaffold.py <siteDir> --plan <SITE_PLAN.md> [--force] [--with-styleguide]
  python scaffold.py <siteDir> --sync
  python scaffold.py <siteDir> --offline [--vendor-from <dir>]      (also combinable with --plan)

The site root is the topic folder (topics/<slug>/), which already holds PLAN.md, topic.json and tmp/ — the
scaffold never touches those. Layout (site.json `pagesDir`, default "pages/"; "" = flat): index.html and assets/
sit at the site root, every other page lives under <pagesDir>. SITE_PLAN.md may set `**Pages dir**: pages/`
(the default) or `**Pages dir**: flat`, and an optional `**Theme**: accent #hex · soft #hex · dark #hex · dark-soft #hex`
line (any subset, any order) that becomes site.json `theme` (contracts §8).
E6/F4: an optional `**Version**: 1.0` header line becomes site.json `version`; an optional `Hours` column of `## Pages`
becomes `pages[].hours` (`25` or a range `20–30` → 25).

--plan   creates <site>/assets and <site>/<pagesDir>; copies assets/style.css, assets/app.js and index.html to the
         root, glossary.html, the reference pages the template ships (indexes.html, notation.html, concepts.html,
         changelog.html — registered under the Reference group when the plan does not list them) and the page-kind
         skeletons _skeleton.html, _module.html, _synthesis.html, _reference.html (and styleguide.html with
         --with-styleguide) into <pagesDir> with their include paths rewritten to ../assets/…; never overwrites a
         copied file without --force; writes assets/site.json from the SITE_PLAN header lines and its `## Pages` table
         (always regenerated — the plan is its source); writes assets/glossary.json as [] and an empty assets/data.js
         stub when absent; then syncs.
--sync   regenerates assets/site.js from assets/site.json and assets/glossary.js from assets/glossary.json, then
         rebuilds assets/data.js from the pages (build_site_data.py).

--offline (G1) vendors KaTeX, highlight.js and the Google Fonts into assets/vendor/ (vendor.py: downloads, or copies
         from --vendor-from <dir>, a folder laid out like assets/vendor/), keeps assets/vendor/manifest.json (source
         URL, bytes, sha256 per file), rewrites every page's CDN <link>/<script> to the local copies and sets site.json
         `"vendor": true` (app.js then loads highlight.js and the F2 font locally). Idempotent; a re-run needs no
         network. A later --plan on a vendored site keeps the flag and re-applies the rewrite to recopied pages.

Single format (SITE_PLAN header `**Format**: single`, optional `**Budget**: 250 KB`): site.json gets
`"mode": "single"`, `"pagesDir": ""` and `"budgetKb"`; the layout is flat; only assets/style.css, assets/app.js
and `_single.html` (the single-page skeleton) are copied — no index.html, glossary.html or other `_*.html`
skeletons. The site folder is then usually topics/<slug>/tmp/site/; bundle.py turns it into one file.
--template <dir> overrides the template folder (tests).

Ends with
  RESULT: tool=scaffold status=PASS|FAIL copied=n skipped=n generated=site.js,glossary.js pages=n [vendored=n fetched=n rewritten=n]
"""
